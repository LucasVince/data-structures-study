def depthFirstSearch(start, g):
    seen = []
    neighbours = []

    neighbours = g.get(start)

    while neighbours != []:
        lastElement = neighbours[len(neighbours) - 1]

        seen.append(lastElement)
        neighbours.pop()

        for n in g.get(lastElement):

            if n in seen or n in neighbours:
                continue

            neighbours.append(n)

    print(seen)

